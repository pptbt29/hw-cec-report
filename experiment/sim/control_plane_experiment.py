"""Profile centralized metadata collection on the acceptance workload."""

from __future__ import annotations

import argparse
import json
import os
import statistics
from typing import Dict, Iterable, List

from .acceptance_experiment import SEEDS, build_config
from .control_plane import (
    AgentObservationSchema,
    ControlPlaneConfig,
    MetadataControlPlaneMeter,
    project_control_plane_scale,
)
from .data_generator import DataGenerator
def _mean_rows(rows: List[Dict], path: Iterable[str]) -> float:
    values = []
    for row in rows:
        value = row
        for key in path:
            value = value[key]
        values.append(float(value))
    return statistics.fmean(values)


def profile_scenario(
    seeds: Iterable[int],
    target: bool,
    config: ControlPlaneConfig,
    include_coalesced_proactive_updates: bool,
) -> Dict:
    runs = []
    for seed in seeds:
        experiment_config = build_config(seed, target)
        workload = experiment_config.workload
        requests = DataGenerator(workload).generate()
        meter = MetadataControlPlaneMeter(
            experiment_config.topology(), config
        )
        meter.account_periodic_reports(workload.duration_ms)

        last_turn = {}
        for request in requests:
            last_turn[request.session_id] = max(
                request.turn_index,
                last_turn.get(request.session_id, -1),
            )

        for request in requests:
            meter.record_snapshot_pull(request.entry_node)
            # One committed KV range update is produced by the executed request.
            # The trace-only estimator does not run the Router.  Ingress is a
            # source-node proxy for the request-completion update; this affects
            # only the A-B/B-C split, not cluster-wide generated bytes.
            meter.record_kv_range_update(request.entry_node)
            if (
                include_coalesced_proactive_updates
                and request.mobility_active
                and request.turn_index < last_turn[request.session_id]
            ):
                # Simple coalescing estimate: at most one committed range report
                # per alternative destination for this trigger.  This is not an
                # event-accurate replay of the KV manager task queue.
                for destination in range(experiment_config.cluster.num_nodes):
                    if destination != request.entry_node:
                        meter.record_kv_range_update(destination)

        run = meter.summary(workload.duration_ms, len(requests))
        run["seed"] = seed
        runs.append(run)

    aggregate_paths = {
        "request_rate_rps": ("request_rate_rps",),
        "collection_generated_mbps": ("collection", "generated_mbps"),
        "collection_link_carried_mbps": (
            "collection", "link_carried_mbps"
        ),
        "pull_generated_mbps": ("per_request_pulls", "generated_mbps"),
        "pull_link_carried_mbps": (
            "per_request_pulls", "link_carried_mbps"
        ),
        "pull_network_latency_mean_ms": (
            "per_request_pulls", "network_latency_ms", "mean"
        ),
        "pull_network_latency_p95_ms": (
            "per_request_pulls", "network_latency_ms", "p95"
        ),
        "pull_network_latency_p99_ms": (
            "per_request_pulls", "network_latency_ms", "p99"
        ),
        "total_generated_mbps": ("total", "generated_mbps"),
        "total_link_carried_mbps": ("total", "link_carried_mbps"),
    }
    aggregate = {
        name: _mean_rows(runs, path)
        for name, path in aggregate_paths.items()
    }
    aggregate["links"] = {}
    for label in runs[0]["links"]:
        aggregate["links"][label] = {
            "throughput_mbps": _mean_rows(
                runs, ("links", label, "throughput_mbps")
            ),
            "capacity_fraction": _mean_rows(
                runs, ("links", label, "capacity_fraction")
            ),
        }
    return {"runs": runs, "mean": aggregate}


def run_profile(
    seeds: Iterable[int],
    node_report_interval_ms: float = 1.0,
    link_report_interval_ms: float = 10.0,
) -> Dict:
    seeds = list(seeds)
    cfg = ControlPlaneConfig(
        node_report_interval_ms=node_report_interval_ms,
        link_report_interval_ms=link_report_interval_ms,
    )
    schema = AgentObservationSchema()
    expected_response_payload = (
        cfg.snapshot_response_metadata_bytes
        + schema.central_float32_bytes
    )
    if cfg.snapshot_response_payload_bytes != expected_response_payload:
        raise ValueError(
            "snapshot response payload does not match the Agent schema"
        )
    output = {
        "assumptions": {
            "collector_node": cfg.collector_node,
            "node_report_interval_ms": cfg.node_report_interval_ms,
            "link_report_interval_ms": cfg.link_report_interval_ms,
            "wire_bytes": {
                "node_report": cfg.node_report_wire_bytes,
                "link_report": cfg.link_report_wire_bytes,
                "kv_range_update": cfg.kv_range_update_wire_bytes,
                "snapshot_query": cfg.snapshot_query_wire_bytes,
                "snapshot_response": cfg.snapshot_response_wire_bytes,
            },
            "unfinished_placement_reported": False,
            "state_age_modeled": False,
            "periodic_reports_begin_after_first_interval": True,
            "profile_kind": (
                "workload-trace metadata estimate; not Router event replay"
            ),
        },
        "agent_schema": {
            "request_feature_dim": schema.request_features,
            "phase_feature_dim": schema.mobility_phase_features,
            "local_feature_dim": schema.local_feature_dim,
            "central_feature_dim": schema.central_feature_dim,
            "observation_dim": schema.observation_dim,
            "action_mask_dim": schema.action_mask_dim,
            "central_continuous_feature_dim": (
                schema.central_continuous_feature_dim
            ),
            "central_flag_feature_dim": schema.central_flag_feature_dim,
            "central_compact_bytes": schema.central_compact_bytes,
            "central_float32_bytes": schema.central_float32_bytes,
            "field_names": {
                "local": schema.local_feature_names,
                "phase": schema.phase_feature_names,
                "per_node": schema.node_feature_names,
                "per_link": schema.link_feature_names,
                "per_node_kv": schema.kv_feature_names,
                "per_node_actions": schema.action_names,
            },
        },
        "seeds": seeds,
        "profiles": {},
    }
    output["metadata_field_groups"] = {
        "running_stage_work": {
            "dimension": 9,
            "wire_type": "float32",
            "field_bytes": 36,
        },
        "waiting_slack_bucket_stage_work": {
            "dimension": 36,
            "wire_type": "float32",
            "field_bytes": 144,
            "slack_bucket_upper_bounds_ms": [0.0, 50.0, 200.0],
        },
        "free_kv_memory_ratio": {
            "dimension": 3,
            "wire_type": "float32",
            "field_bytes": 12,
        },
        "recent_p99_ttft": {
            "dimension": 3,
            "wire_type": "float32",
            "field_bytes": 12,
        },
        "link_bandwidth_and_rtt": {
            "dimension": 6,
            "wire_type": "float32",
            "field_bytes": 24,
        },
        "link_available": {
            "dimension": 3,
            "wire_type": "uint8",
            "field_bytes": 3,
        },
        "complete_latest_kv": {
            "dimension": 3,
            "wire_type": "uint8",
            "field_bytes": 3,
        },
        "kv_prefix_and_recovery_times": {
            "dimension": 9,
            "wire_type": "float32",
            "field_bytes": 36,
        },
    }
    bytes_per_pull = (
        cfg.snapshot_query_wire_bytes + cfg.snapshot_response_wire_bytes
    )
    output["request_rate_sensitivity"] = {}
    for request_rate in (10, 100, 1000, 10000):
        pull_mbps = request_rate * bytes_per_pull * 8.0 / 1e6
        execution_update_mbps = (
            request_rate * cfg.kv_range_update_wire_bytes * 8.0 / 1e6
        )
        proactive_upper_mbps = 3.0 * execution_update_mbps
        periodic_mbps = 8.0 * (
            3.0 * 1000.0 / cfg.node_report_interval_ms
            * cfg.node_report_wire_bytes
            + 3.0 * 1000.0 / cfg.link_report_interval_ms
            * cfg.link_report_wire_bytes
        ) / 1e6
        output["request_rate_sensitivity"][str(request_rate)] = {
            "pull_generated_mbps": pull_mbps,
            "collection_execution_only_generated_mbps": (
                periodic_mbps + execution_update_mbps
            ),
            "collection_proactive_upper_generated_mbps": (
                periodic_mbps + proactive_upper_mbps
            ),
            "total_proactive_upper_generated_mbps": (
                periodic_mbps + proactive_upper_mbps + pull_mbps
            ),
            "all_generated_traffic_fraction_of_25gbps_reference": (
                periodic_mbps + proactive_upper_mbps + pull_mbps
            ) * 1e6 / 25e9,
        }
    for target, scenario in ((False, "baseline"), (True, "target_150pct")):
        output["profiles"][scenario] = {
            "execution_updates_only": profile_scenario(
                seeds,
                target,
                cfg,
                include_coalesced_proactive_updates=False,
            ),
            "with_coalesced_proactive_updates": profile_scenario(
                seeds,
                target,
                cfg,
                include_coalesced_proactive_updates=True,
            ),
        }
    target_rate = output["profiles"]["target_150pct"][
        "with_coalesced_proactive_updates"
    ]["mean"]["request_rate_rps"]
    output["node_count_sensitivity"] = {
        "assumptions": {
            "request_rate_rps": target_rate,
            "topology": "full_mesh",
            "kv_range_events_excluded": True,
            "note": (
                "logical generated traffic; physical link load depends on "
                "collector placement and routing"
            ),
        },
        "rows": {},
    }
    for num_nodes in (3, 10, 25, 50, 100):
        num_links = num_nodes * (num_nodes - 1) // 2
        output["node_count_sensitivity"]["rows"][str(num_nodes)] = (
            project_control_plane_scale(
                num_nodes=num_nodes,
                num_links=num_links,
                request_rate_rps=target_rate,
                config=cfg,
            )
        )
    return output


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", default=",".join(map(str, SEEDS)))
    parser.add_argument("--node-report-ms", type=float, default=1.0)
    parser.add_argument("--link-report-ms", type=float, default=10.0)
    parser.add_argument(
        "--output",
        default=os.path.join(
            os.path.dirname(os.path.dirname(os.path.dirname(__file__))),
            "profile_output",
            "control_plane_summary.json",
        ),
    )
    args = parser.parse_args()
    seeds = [int(value) for value in args.seeds.split(",") if value.strip()]
    output = run_profile(
        seeds,
        node_report_interval_ms=args.node_report_ms,
        link_report_interval_ms=args.link_report_ms,
    )
    parent = os.path.dirname(os.path.abspath(args.output))
    os.makedirs(parent, exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        json.dump(output, handle, ensure_ascii=False, indent=2)
    print(json.dumps(output, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
